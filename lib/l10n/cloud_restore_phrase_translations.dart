String? translatedCloudRestorePhrase(String text, int index) {
  final summary =
      RegExp(r'^(\d+) coins · (\d+) gems · (\d+) adventures$').firstMatch(text);
  if (summary != null) {
    return _restoreDynamic['summary']![index]
        .replaceAll('{coins}', summary[1]!)
        .replaceAll('{gems}', summary[2]!)
        .replaceAll('{adventures}', summary[3]!);
  }
  final confirmation = RegExp(
          r'^Replace this device with revision (\d+) from (.*?)\? This backup may be older than your local progress\.\n\nOn this device: (.*?)\nCloud backup: (.*?)\n\nA separate recovery copy is saved first\. You can undo this in Account Info\.$',
          dotAll: true)
      .firstMatch(text);
  if (confirmation != null) {
    return _restoreDynamic['confirmation']![index]
        .replaceAll('{revision}', confirmation[1]!)
        .replaceAll('{date}', confirmation[2]!)
        .replaceAll(
            '{local}',
            translatedCloudRestorePhrase(confirmation[3]!, index) ??
                confirmation[3]!)
        .replaceAll(
            '{cloud}',
            translatedCloudRestorePhrase(confirmation[4]!, index) ??
                confirmation[4]!);
  }
  if (text.startsWith(
          'This device is not based on the latest cloud revision') &&
      text.endsWith(
          'The cloud copy may be older than this device. Keep local progress unless you have compared the backups.')) {
    return _restoreDynamic['conflict']![index];
  }
  return null;
}

