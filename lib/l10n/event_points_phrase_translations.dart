String? translatedEventPointsPhrase(String text, int index) {
  final exact = eventPointsPhraseTranslations[text];
  if (exact != null) return exact[index];
  for (final entry in eventPointsPhraseTranslations.entries) {
    if (!entry.key.contains('{value}')) continue;
    final parts = entry.key.split('{value}');
    if (text.startsWith(parts.first) &&
        text.endsWith(parts.last) &&
        text.length >= parts.first.length + parts.last.length) {
      final value =
          text.substring(parts.first.length, text.length - parts.last.length);
      return entry.value[index].replaceAll('{value}', value);
    }
  }
  return null;
}
